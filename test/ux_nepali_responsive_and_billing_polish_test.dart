        );
        await tester.pumpAndSettle();

        expect(find.text('अघिल्लो कोटेशन दर'), findsOneWidget);
        expect(find.text('बासमती चामल २५ केजी'), findsOneWidget);
        expect(find.text('तोरीको तेल १ लिटर'), findsOneWidget);

        // Apply line discount on item 1 -> total discount summary appears.
        await tester.enterText(find.byType(TextFormField).at(1), '100');
        await tester.pump();
        expect(find.text('कुल छुट'), findsOneWidget);
        expect(tester.takeException(), isNull);
      } finally {
        await tester.pumpWidget(const SizedBox.shrink());
        await tester.pumpAndSettle();
      }
    },
  );

