void _setViewport(WidgetTester tester, Size size) {
  tester.view.devicePixelRatio = 1;
  tester.view.physicalSize = size;
  addTearDown(tester.view.resetPhysicalSize);
  addTearDown(tester.view.resetDevicePixelRatio);
}

void main() {
  setUp(() {
    SharedPreferences.setMockInitialValues({});
  });

  test('Nepali l10n strings have accurate Devanagari spelling', () {
    final ne = AppLocalizationsNe();
    expect(ne.statusReceived, 'हेरियो');
    expect(ne.statusReceived.contains('\u094D'), isFalse);
    expect(ne.filterOrders, 'अर्डरहरू खोज्नुहोस्');
    expect(ne.planFree, 'निःशुल्क');
    expect(ne.autoGenerated, 'स्वचालित');
    expect(ne.columnName, 'नाम');
    expect(ne.columnRole, 'भूमिका');
  });

  testWidgets(
    'Nepali mobile web shell, top bar, KPI grid, and shortcuts dialog render without overflow at 390x844',
    (tester) async {
      _setViewport(tester, const Size(390, 844));
      final router = GoRouter(
        initialLocation: '/owner/dashboard',
        routes: [
          ShellRoute(
            builder: (context, state, child) {
              final l10n = AppLocalizations.of(context);
              return WebAppShell(
                navItems: [
                  WebNavItem(
                    label: l10n.dashboard,
                    path: '/owner/dashboard',
                    icon: Icons.dashboard,
                  ),
                  WebNavItem(
                    label: l10n.inventory,
                    path: '/owner/inventory',
                    icon: Icons.inventory,
                  ),
                  WebNavItem(
                    label: l10n.billing,
                    path: '/owner/billing',
                    icon: Icons.receipt,
                  ),
                  WebNavItem(
                    label: l10n.customers,
                    path: '/owner/customers',
                    icon: Icons.store,
                  ),
                  WebNavItem(
                    label: l10n.orders,
                    path: '/owner/orders',
                    icon: Icons.shopping_cart,
                  ),
                ],
                child: child,
              );
            },
            routes: [
              GoRoute(
                path: '/owner/dashboard',
                builder: (_, _) => SingleChildScrollView(
                  padding: const EdgeInsets.all(16),
                  child: WebDashboardKpiGrid(
                    stats: const AsyncValue.data(
                      OwnerDashboardStats(
                        todaySales: 0,
                        yesterdaySales: 0,
                        totalDues: 1250000,
                        lowStockCount: 0,
                        pendingOrders: 0,
                      ),
                    ),
                    onRetry: () {},
                  ),
                ),
              ),
            ],
          ),
        ],
      );
      try {
        await tester.pumpWidget(
          ProviderScope(
            overrides: [
              authProvider.overrideWith(_OwnerAuth.new),
              unreadNotificationCountProvider.overrideWith((ref) async => 3),
              notificationListProvider.overrideWith((ref) => Stream.value([])),
            ],
            child: MaterialApp.router(
              routerConfig: router,
              theme: WebTheme.light(),
              locale: const Locale('ne'),
              localizationsDelegates: AppLocalizations.localizationsDelegates,
              supportedLocales: AppLocalizations.supportedLocales,
            ),
          ),
        );
        await tester.pumpAndSettle();

        expect(tester.takeException(), isNull);
        // Zero sales today must not render an empty trend badge.
        expect(find.text('0 उत्पादनहरू'), findsOneWidget);
        expect(find.text('0 अर्डरहरू'), findsOneWidget);

        // Open shortcuts modal in Nepali on 390px without overflow.
        unawaited(
          showWebShortcutsDialog(
            tester.element(find.byType(WebDashboardKpiGrid)),
            navItems: const [
              WebNavItem(
                label: 'ड्यासबोर्ड',
                path: '/owner/dashboard',
                icon: Icons.dashboard,
              ),
              WebNavItem(
                label: 'बिलिङ',
                path: '/owner/billing',
                icon: Icons.receipt,
              ),
            ],
            canCreateBill: true,
          ),
        );
        await tester.pumpAndSettle();
        expect(find.text('किबोर्ड सर्टकटहरू'), findsOneWidget);
        expect(tester.takeException(), isNull);
      } finally {
        await tester.pumpWidget(const SizedBox.shrink());
        await tester.pumpAndSettle();
        router.dispose();
      }
    },
  );

  testWidgets(
    'WebBillFormContent keeps empty state visible at 390px NE and uses two-pane layout at 1280px',
    (tester) async {
      // 1. Narrow 390x844 Nepali: empty state must stay within viewport width.
      _setViewport(tester, const Size(390, 844));
      await tester.pumpWidget(
        ProviderScope(
          key: UniqueKey(),
          overrides: [
            authProvider.overrideWith(_OwnerAuth.new),
            productListProvider.overrideWith((ref, q) async => const []),
            customerListProvider.overrideWith((ref, q) async => const []),
          ],
          child: MaterialApp(
            theme: WebTheme.light(),
            locale: const Locale('ne'),
            localizationsDelegates: AppLocalizations.localizationsDelegates,
            supportedLocales: AppLocalizations.supportedLocales,
            home: const Scaffold(body: WebBillFormContent()),
          ),
        ),
      );
      await tester.pumpAndSettle();

      final emptyText = find.text('बिलमा उत्पादन थप्नुहोस्');
      expect(emptyText, findsOneWidget);
      final emptyRect = tester.getRect(emptyText);
      expect(emptyRect.left, greaterThanOrEqualTo(0));
      expect(emptyRect.right, lessThanOrEqualTo(390));
      expect(find.text('स्वचालित'), findsOneWidget);
      expect(find.text('AUTO'), findsNothing);
      expect(tester.takeException(), isNull);

      // 2. Desktop 1280x800 (content ~960px): checkout rail sits side-by-side above fold.
      tester.view.physicalSize = const Size(960, 720);
      await tester.pumpAndSettle();

      final billSummaryRect = tester.getRect(find.byType(BillSummary));
      expect(
        billSummaryRect.left,
        greaterThan(500),
        reason: 'Checkout rail should sit on the right side at 1280px desktop',
      );
      expect(
        billSummaryRect.top,
        lessThan(500),
        reason: 'Checkout totals should stay above the fold',
      );
      expect(tester.takeException(), isNull);

      await tester.pumpWidget(const SizedBox.shrink());
      await tester.pumpAndSettle();
    },
  );

  testWidgets(
    'BillPaymentSheet shows live remaining due and inline error on partial payment',
    (tester) async {
      await tester.pumpWidget(
        ProviderScope(
          overrides: [
            authProvider.overrideWith(_OwnerAuth.new),
            customerListProvider.overrideWith(
              (ref, q) async => const [
                Customer(
                  id: 'c1',
                  businessId: 'biz-1',
                  memberId: 'cm1',
                  shopName: 'Everest Mart',
                ),
              ],
            ),
          ],
          child: MaterialApp(
            theme: AppTheme.light(),
            localizationsDelegates: const [
              AppLocalizations.delegate,
              GlobalMaterialLocalizations.delegate,
              GlobalWidgetsLocalizations.delegate,
              GlobalCupertinoLocalizations.delegate,
            ],
            supportedLocales: AppLocalizations.supportedLocales,
            home: const Scaffold(
              body: BillPaymentSheet(
                grandTotal: 100000, // रू 1,000.00
                initialCustomerId: 'c1',
                initialCustomerName: 'Everest Mart',
              ),
            ),
          ),
        ),
      );
      await tester.pumpAndSettle();

      await tester.tap(find.text('Partial'));
      await tester.pumpAndSettle();

      final amountField = find.widgetWithText(TextFormField, 'Amount paid');
      await tester.enterText(amountField, '400.25');
      await tester.pump();

      expect(find.text('Remaining due'), findsOneWidget);
      expect(find.text('रू 599.75'), findsOneWidget);

      // Exceeding grand total shows inline error immediately.
      await tester.enterText(amountField, '1500');
      await tester.pump();
      expect(find.text('Amount cannot exceed the grand total'), findsOneWidget);
      expect(tester.takeException(), isNull);
    },
  );

